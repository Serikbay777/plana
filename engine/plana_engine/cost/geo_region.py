"""Координаты посадки → регион (для выбора ставки УПСС).

Тупая версия v0: статическая таблица крупных городов РК с координатами;
region_from_coords возвращает ближайший город по формуле гаверсинуса.
Это НЕ геокодер и НЕ привязка к КАТО — лишь грубый выбор регионального
показателя ₸/м² (главный фактор стоимости: разброс по регионам >2×).
Город, отсутствующий в таблице ставок aggregate_cost, всё равно вернётся
по имени и упадёт на ставку 'default' — это честно для v0.
"""
from __future__ import annotations

from math import asin, cos, radians, sin, sqrt

# (город, lat, lon) — приблизительные координаты центров. Плейсхолдер v0.
_CITIES: list[tuple[str, float, float]] = [
    ("Алматы", 43.2389, 76.8897),
    ("Астана", 51.1605, 71.4704),
    ("Шымкент", 42.3417, 69.5901),
    ("Актобе", 50.2839, 57.1670),
    ("Караганда", 49.8047, 73.1094),
    ("Тараз", 42.9000, 71.3667),
    ("Павлодар", 52.2873, 76.9674),
    ("Усть-Каменогорск", 49.9489, 82.6286),
    ("Семей", 50.4111, 80.2275),
    ("Атырау", 47.0945, 51.9238),
    ("Костанай", 53.2198, 63.6354),
    ("Кызылорда", 44.8488, 65.4823),
    ("Уральск", 51.2333, 51.3667),
    ("Петропавловск", 54.8753, 69.1628),
    ("Актау", 43.6510, 51.1694),
    ("Туркестан", 43.3000, 68.2500),
    ("Кокшетау", 53.2833, 69.3833),
    ("Талдыкорган", 45.0156, 78.3739),
]

# Если ближайший центр дальше — координаты, вероятно, вне известных центров.
_MAX_MATCH_KM = 250.0


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Расстояние по большому кругу (км)."""
    r = 6371.0
    dlat = radians(lat2 - lat1)
    dlon = radians(lon2 - lon1)
    a = (
        sin(dlat / 2) ** 2
        + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon / 2) ** 2
    )
    return 2 * r * asin(sqrt(a))


def nearest_city(lat: float, lon: float) -> tuple[str, float]:
    """Ближайший город из таблицы и расстояние до него (км)."""
    best_name = "default"
    best_km = float("inf")
    for name, clat, clon in _CITIES:
        km = _haversine_km(lat, lon, clat, clon)
        if km < best_km:
            best_km, best_name = km, name
    return best_name, best_km


def region_from_coords(lat: float, lon: float) -> str:
    """Координаты → имя региона (ближайший крупный город РК).

    Если ближайший центр дальше _MAX_MATCH_KM — возвращаем 'default'
    (грубая защита от случайных/далёких координат).
    """
    name, km = nearest_city(lat, lon)
    return name if km <= _MAX_MATCH_KM else "default"
